#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    double x;  // вхідний аргумент
    double R1; // вхідний параметр 1
    double R2; // вхідний параметр 2
    double y;  // результат обчислення виразу

    cout << "R1 = "; cin >> R1;
    cout << "R2 = "; cin >> R2;
    cout << "x = "; cin >> x;

    // розгалуження в повній формі для графічної функції Варіанту 16
    if (x <= -6)
    {
        y = R2; // горизонтальна ділянка зліва
    }
    else
    {
        if (x > -6 && x <= -2 * R2)
        {
            y = -R2 - (R2 / (2 * R2 - 6)) * (x - (-6)); // лінійна ділянка
        }
        else
        {
            if (x > -2 * R2 && x <= 0)
            {
                y = R2 - sqrt(R2 * R2 - (x + R2) * (x + R2)); // дуга кола
            }
            else
            {
                if (x > 0 && x <= R1)
                {
                    y = -sqrt(R1 * R1 - x * x); // дуга нижнього кола
                }
                else
                {
                    if (x > R1 && x <= 2 * R1 + 1)
                    {
                        y = -1.0 / (2 * R1 + 1 - R1) * (x - R1); // похила пряма
                    }
                    else
                    {
                        y = -R1; // горизонтальна полиця справа
                    }
                }
            }
        }
    }

    cout << endl;
    cout << "y = " << y << endl;

    cin.get();
    return 0;
}